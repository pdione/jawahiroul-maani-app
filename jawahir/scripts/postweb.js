// Post-processes dist/: PWA tags in index.html + a service worker that caches the whole app for offline use.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const DIST = 'dist';
const walk = (d) =>
  fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => {
    const p = path.join(d, e.name);
    return e.isDirectory() ? walk(p) : [p];
  });

// 1. index.html : manifest, icons, service-worker registration
const f = path.join(DIST, 'index.html');
let h = fs.readFileSync(f, 'utf8');
const tags = `
<link rel="manifest" href="/manifest.webmanifest">
<link rel="apple-touch-icon" href="/apple-touch-icon.png">
<meta name="theme-color" content="#1E6A57">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Jawahir">
<script>if('serviceWorker' in navigator){window.addEventListener('load',function(){navigator.serviceWorker.register('/sw.js').catch(function(){})})}</script>`;
if (!h.includes('manifest.webmanifest')) h = h.replace('</head>', tags + '\n</head>');
h = h.replace(/<html[^>]*>/, '<html lang="fr">');
fs.writeFileSync(f, h);

// 2. service worker with the exact list of files (versioned by content hash)
const skip = new Set(['sw.js', 'metadata.json', '_redirects']);
const files = walk(DIST)
  .map((p) => '/' + path.relative(DIST, p).split(path.sep).join('/'))
  .filter((u) => !skip.has(u.slice(1)));
const hash = crypto.createHash('sha1');
for (const u of files) hash.update(u).update(fs.readFileSync(path.join(DIST, u)));
const version = hash.digest('hex').slice(0, 10);

const sw = `// GENERATED by scripts/postweb.js
const CACHE = 'jawahir-${version}';
const FILES = ${JSON.stringify(['/', ...files])};

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('jawahir-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  // page navigations (any route of the single-page app) -> cached index.html
  if (req.mode === 'navigate') {
    event.respondWith(caches.match('/index.html').then((r) => r || caches.match('/')).then((r) => r || fetch(req)));
    return;
  }
  event.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
fs.writeFileSync(path.join(DIST, 'sw.js'), sw);
console.log('postweb : ' + files.length + ' fichiers en cache, version ' + version);
